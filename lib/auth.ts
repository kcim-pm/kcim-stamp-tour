// lib/auth.ts — 관리자 세션 토큰 발급·검증 (순수 함수, 단위 테스트 대상)
//
// DB·쿠키·환경변수를 직접 읽지 않는다. 비밀키와 현재 시각은 전부 인자로 받는다.
// 그래야 테스트에서 시각을 마음대로 넣어 「만료」를 재현할 수 있다.
// Node 내장 crypto 만 쓴다 (createHmac, timingSafeEqual). 새 패키지 없음.

// ── 상수 ──────────────────────────────────────────────
// 쿠키 이름 "admin_session", 수명 12시간(43200초). 명세 5.3.

// ── 토큰 형식 ─────────────────────────────────────────
// "<만료시각>.<서명>"
//   만료시각: 유닉스 초(정수). 발급 시각 + 12시간
//   서명:     HMAC-SHA256(만료시각 문자열, 비밀키) 를 hex 로
// 서버만 비밀키를 알므로, 만료시각을 고치면 서명이 안 맞아 위조로 걸린다.

// ── 함수 1: 토큰 발급 ─────────────────────────────────
// createSessionToken(secret, now)
//   1. 만료시각 = now + 43200
//   2. 서명 = HMAC(만료시각, secret)
//   3. "만료시각.서명" 을 돌려준다

// ── 함수 2: 토큰 검증 ─────────────────────────────────
// verifySessionToken(token, secret, now) → true / false
//   1. "." 으로 나눠 두 조각이 아니면 false
//   2. 만료시각이 정수가 아니면 false
//   3. 기대 서명을 다시 계산해 받은 서명과 비교한다
//      - 길이가 다르면 false
//      - 길이가 같으면 timingSafeEqual 로 비교 (한 글자씩 끊어 비교하지 않는다)
//   4. 만료시각 <= now 이면 false (만료)
//   5. 전부 통과하면 true
//   예외를 던지지 않고 항상 boolean 만 돌려준다. 호출하는 쪽이 if 하나로 끝나게.

// ── 함수 3: 비밀번호 비교 ─────────────────────────────
// isPasswordCorrect(input, expected) → true / false
//   길이가 다르면 바로 false, 같으면 timingSafeEqual.
//   명세 7.2 「길이가 같을 때만 통과하는 상수 시간 비교」.
//   (=== 로 비교하면 앞글자부터 틀린 자리에서 멈춰 응답 시간이 달라진다)

// ── 함수 4: 로그인 뒤 돌아갈 경로 검사 ────────────────
// safeNextPath(raw) → string
//   /admin/login?next=/qr 처럼 받은 값을 그대로 redirect 에 쓰면
//   next=https://evil.com 같은 외부 주소로 보내질 수 있다.
//   규칙: "/" 로 시작하고 "//" 로 시작하지 않으면 그대로, 아니면 "/admin".
//   값이 없거나 빈 문자열이어도 "/admin".
