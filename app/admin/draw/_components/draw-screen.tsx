// 추첨·발표 화면 본체 (클라이언트). spec 3.4, A-09~A-18, A-24~A-26, D-10, D-18, D-19
//
// 의사 코드 (작업 9). 아직 구현 전이다.
//
// 【이 컴포넌트가 하는 일】
//   경품 목록 순서대로 한 경품씩 추첨을 진행한다.
//   준비 → 추첨 중 → 결과(임시) → (부재자 재추첨) → 확정 → [다음 경품 →] 순서로 화면이 바뀐다.
//
// ─────────────────────────────────────────────
// 【가장 중요한 원칙: 단계는 서버 데이터를 보고 계산한다】
//   「지금 어느 단계인가」를 화면에 따로 저장하지 않는다. 서버에서 받은 회차 목록을 보고 매번 판단한다.
//   그래야 창을 닫았다 다시 열거나 새로고침해도 같은 단계로 돌아온다 (spec 3.4, D-10).
//
// 【서버에서 받아 오는 것】
//   - 경품 목록 (경품 API)
//   - 회차 목록과 추첨 후보 수 (추첨 API 의 조회)
//   처음 열 때, 그리고 조작이 실패했을 때 두 API 를 함께 다시 부른다.
//
// 【화면에서만 기억하는 것】
//   - 방금 확정한 회차: [다음 경품 →]을 누를 때까지 그 결과를 계속 보여 주기 위해
//   - 보고 있는 이전 회차: [이전 결과]로 연 과거 회차
//   - 부재자로 고른 번호들
//   - 준비 단계 입력값: 「이전 당첨자 제외」 켜짐/꺼짐, 당첨 인원
//   - 연출 중인지, 일시정지인지
//   - 요청 중인지: 요청 중에는 모든 조작 버튼을 막는다. 두 번 눌러 회차가 두 개 생기는 것을 막기 위해서다.
//   - 오류 문구
//
// ─────────────────────────────────────────────
// 【단계 판단】 화면을 그릴 때마다 위에서부터 차례로 확인한다
//   1. 임시 회차가 있고 연출 중이면 → 「추첨 중」
//   2. 임시 회차가 있으면 → 「결과(임시)」
//   3. 방금 확정한 회차가 있으면 → 「확정 후」 (그 회차를 보여 준다)
//   4. 지금 차례인 경품이 없으면 → 「모두 끝남」
//   5. 그 밖 → 「준비」
//   지금 차례인 경품은 lib/draw-state.ts 의 currentPrize 로 구한다. 브라우저에서도 그대로 쓸 수 있는 함수다.
//
//   「방금 확정한 회차」를 따로 기억하는 이유:
//     확정하는 순간 지금 차례 경품이 다음 경품으로 넘어간다. 이것을 기억하지 않으면 확정한 결과가 사라지고
//     곧바로 다음 경품 준비 화면이 떠 버린다. 관객이 확정된 번호를 볼 시간이 없다.
//
// ─────────────────────────────────────────────
// 【조작별 동작】
//   [추첨 시작]  (준비 단계)
//     1. 지금 경품 번호, 당첨 인원, 「이전 당첨자 제외」 값으로 추첨 API 를 부른다.
//     2. 성공하면 받은 회차를 목록에 넣고 연출을 시작한다.
//     3. 실패하면 오류 문구를 보여 주고 데이터를 다시 불러온다. 예: 후보 없음, 확정 안 한 회차 있음.
//
//   번호 누르기  (결과(임시) 단계)
//     누른 번호를 「부재자로 고른 번호」에 넣거나 뺀다.
//
//   [선택 번호 재추첨]  (결과(임시) 단계, 고른 번호가 있을 때만)
//     1. 고른 번호들로 재추첨 API 를 부른다.
//     2. 성공하면 받은 회차로 바꾸고 고른 번호를 비운다. 새로 뽑힌 번호는 잠깐 강조한다.
//
//   [✓ 당첨 확정]  (결과(임시) 단계)
//     1. 확정 API 를 부른다.
//     2. 성공하면 받은 회차로 바꾸고, 이 회차를 「방금 확정한 회차」로 기억한다.
//
//   [선물 주기] / [지급 완료]  (확정 후, 이전 결과)  spec 3.4, A-20
//     아직 지급하지 않은 번호를 누르면:
//       1. 「지급」으로 지급 API 를 부른다.
//     이미 지급한 번호(「지급 완료」)를 누르면:
//       1. 확인 창을 띄운다: 「N번의 지급을 취소할까요?」. 무대 옆에서 잘못 눌러 취소되는 일을 막기 위해서다.
//       2. 취소를 고르면 아무것도 하지 않는다. 확인을 고르면 「지급 취소」로 지급 API 를 부른다.
//     공통: 실패하면 오류 문구를 보여 준다. 성공이든 실패든 데이터를 다시 불러온다 (콘솔에서 먼저 바꿨을 수 있다).
//
//   [명단 복사]  (확정 후)
//     「5등 OO경품: 7, 42, 108」 모양의 글자를 만들어 클립보드에 복사하고 「복사했습니다」를 잠깐 보여 준다.
//
//   [다음 경품 →]  (확정 후)
//     「방금 확정한 회차」 기억을 지운다. 서버는 부르지 않는다.
//     그러면 단계 판단이 자동으로 다음 경품의 「준비」가 된다. 당첨 인원 입력란은 다음 경품의 인원으로 채운다.
//
//   [이전 결과]
//     확정된 회차 목록을 보여 주고, 하나를 고르면 그 결과를 화면 위에 겹쳐 보여 준다. [닫기]로 돌아온다.
//
// ─────────────────────────────────────────────
// 【추첨 연출】 A-14, 방식은 아직 미정
//   결과는 서버가 이미 정했다. 연출은 그 결과를 극적으로 보여 줄 뿐이다.
//   최소 구현: 3초 동안 가운데에서 번호가 빠르게 바뀌는 효과와 효과음을 보여 준 뒤 결과 격자를 보여 준다.
//   [일시정지]: 3초 타이머를 멈추고, 다시 누르면 남은 시간부터 이어 간다.
//   연출 중인지는 화면에만 기억하므로, 연출 도중 새로고침하면 연출 없이 바로 결과(임시) 단계가 나온다.
//   효과음 파일은 연출 방식이 정해지면 public/sounds/ 에 둔다.
//
// ─────────────────────────────────────────────
// 【화면 구성】 가로 16:9
//   ① 머리글: 「KCIM BIMlize Con 2026 · LUCKY DRAW」
//   ② 경품 표시: 「N등 경품」 작은 라벨과 경품 이름(크게). 오른쪽에 「N명 추첨」
//   ③ 가운데 (단계마다 다름)
//      - 준비: 후보 수, 「이전 당첨자 제외」 스위치, 당첨 인원 입력(기본값은 경품 목록의 인원), [추첨 시작]
//        후보 수는 스위치가 켜져 있으면 candidateCount, 꺼져 있으면 completedCount (둘 다 draws 조회 응답에 있음)
//      - 추첨 중: 연출, [일시정지]
//      - 결과(임시): 당첨 번호 격자(번호를 눌러 고를 수 있음), 안내문
//        「부재자가 있으면 해당 번호를 모두 선택한 뒤 [선택 번호 재추첨]을 눌러주세요」, [✓ 당첨 확정] [선택 번호 재추첨]
//      - 확정 후: 「확정」 표시가 붙은 격자, 번호마다 [선물 주기], [명단 복사]
//        마지막 경품이었으면 [다음 경품 →] 대신 「모든 추첨이 끝났습니다」
//      - 모두 끝남: 「모든 추첨이 끝났습니다」
//   ④ 하단 버튼 줄: [일시정지] [추첨 시작] [이전 결과] [다음 경품 →]
//      버튼 위치는 단계와 상관없이 고정하고, 지금 쓸 수 없는 버튼은 흐리게 막는다.
//      위치가 바뀌면 무대 옆의 운영자가 헷갈린다.
//   ⑤ 오른쪽 「당첨 현황」 패널 (winners-panel)
//   ⑥ 오류 문구가 있으면 아래에 빨간 줄

