// 관리자 콘솔 본체 (클라이언트). spec 3.3 통계·참가자 목록·자동 갱신, A-04~A-08, A-20, A-21
//
// 의사 코드 (작업 8). 아직 구현 전이다.
//
// 【이 컴포넌트가 하는 일】
//   참가자 현황을 불러와 통계와 목록을 보여 주고, 지급 체크와 삭제를 처리한다. 자동 갱신도 여기서 연결한다.
//
// 【기억하는 값】
//   - 불러온 데이터 (통계, 참가자 목록)
//   - 필터: 「전체」 또는 「완주자 중 선물 미지급자」
//   - 불러오는 중인지
//   - 오류 문구 (불러오기 실패 시)
//   - 마지막으로 불러온 시각
//
// 【기능 1: 불러오기】
//   1. 「불러오는 중」으로 표시한다.
//   2. 지금 필터 값으로 참가자 API 를 부른다 (adminFetch).
//   3. 성공하면 데이터와 「마지막 갱신 시각」을 바꾸고 오류 문구를 지운다.
//      실패하면 오류 문구만 보여 주고, 이전 데이터는 지우지 않는다. 통신이 잠깐 끊겨도 표가 사라지지 않게 하려는 것이다.
//   4. 「불러오는 중」 표시를 끈다.
//   이 기능은 다음 때 실행된다: 처음 열 때, 필터를 바꿀 때, 자동 갱신 1분마다(use-auto-refresh), [새로고침]을 누를 때.
//
// 【기능 2: 지급 체크】  A-20
//   1. 체크박스를 켜면 「지급」, 끄면 「지급 취소」로 지급 API 를 부른다.
//   2. 실패하면 문구를 알림 창으로 보여 준다. 예: 발표 화면에서 먼저 지급했으면 「이미 지급 처리된 당첨자입니다」.
//   3. 성공이든 실패든 목록을 다시 불러온다. 다른 창에서 바뀐 내용까지 한 번에 맞추기 위해서다.
//
// 【기능 3: 삭제】  A-08
//   1. 확인 창을 띄운다: 「N번 참가자를 삭제할까요? 방문 기록과 당첨 기록도 함께 지워집니다.」
//   2. 취소하면 아무것도 하지 않는다.
//   3. 확인하면 삭제 API 를 부르고, 실패하면 알림 창을 띄운다. 그다음 목록을 다시 불러온다.
//
// 【화면 구성】 위에서부터
//   ① 통계: 전체 참가자, 완주자, 진행 중, 지급 완료
//      지급 진행률: 「지급 완료 / 당첨」과 비율(%). 당첨이 0이면 비율 대신 「-」
//   ② 갱신 줄: [자동 갱신 1분] 스위치, [새로고침] 버튼(불러오는 중에는 막음), 「마지막 갱신 시:분:초」, 오류 문구(빨강)
//   ③ 참가자 목록: 필터 선택(전체 / 완주자 중 선물 미지급자) + 참가자 표(participant-table)
//
// 【구역 열】 응답의 zones(구역 코드와 이름, 구역 순서)로 표의 열 순서와 열 제목을 정한다 (spec 5.3).
//   참가자 줄의 visits 는 구역 코드로 찾는다.
//
// 【참고】 발표 화면에서 확정하거나 지급한 내용은 다음 갱신 때 반영된다 (spec 3.3 마지막 문단).

