// 경품 목록 등록·수정 (클라이언트). spec 3.3 「경품 목록」, A-12, D-19
//
// 의사 코드 (작업 8). 아직 구현 전이다.
//
// 【이 컴포넌트가 하는 일】
//   행사 전에 경품(등급, 이름, 당첨 인원, 순서)을 등록하고 고친다. 추첨은 이 순서대로 진행된다.
//   이미 추첨한 경품은 고칠 수 없게 잠근다.
//
// 【기억하는 값】
//   - 편집 중인 경품 표 (각 줄: 경품 번호(새 줄은 없음), 등급, 이름, 당첨 인원, 순서, 이미 추첨했는지)
//   - 저장하지 않은 변경이 있는지
//   - 저장 중인지
//   - 알림 문구 (「저장했습니다」 또는 오류 문구)
//
// 【기능 1: 불러오기】
//   처음 열 때 경품 목록 API 를 불러 표를 채운다. 「저장하지 않은 변경 없음」으로 둔다.
//   1분 자동 갱신에는 넣지 않는다. 입력하는 도중에 갱신되면 고치던 값이 덮어써지기 때문이다.
//
// 【기능 2: 편집】
//   - [+ 경품 추가]: 표 끝에 빈 줄을 추가한다. 순서 칸에는 마지막 순서 + 1 을 미리 넣는다.
//   - 줄 삭제: 아직 추첨하지 않은 줄만 표에서 뺀다.
//   - 값 고치기: 아직 추첨하지 않은 줄의 입력란만 고칠 수 있다. 고치면 「저장하지 않은 변경 있음」.
//   - 이미 추첨한 줄: 입력란 대신 글자로 보여 주고 「추첨함」 표시를 붙인다. 삭제 버튼도 없다.
//     (서버도 PRIZE_ALREADY_DRAWN 으로 막지만, 화면에서 먼저 막아 헷갈리지 않게 한다)
//
// 【기능 3: 저장】
//   1. 화면에서 먼저 검사한다: 이름이 비었거나, 등급·당첨 인원·순서가 정수가 아니거나, 당첨 인원이 1보다 작으면
//      그 칸을 빨갛게 표시하고 멈춘다. (서버도 같은 검사를 한다. 화면 검사는 빨리 알려 주기 위한 것이다)
//   2. 표 전체를 경품 저장 API 로 보낸다. 새 줄은 경품 번호 없이 보낸다 (spec 5.3 「id 가 없으면 새로 만든다」).
//   3. 성공하면 응답으로 표를 다시 채우고 「저장했습니다」를 보여 준다.
//   4. 실패하면 오류 문구를 보여 준다.
//      「이미 추첨한 경품」 오류면, 그사이 발표 화면에서 추첨한 것이므로 목록을 다시 불러온다.
//
// 【화면】
//   제목 「경품 목록」, 안내문 「위에서부터 순서대로 추첨합니다. 추첨한 경품은 수정할 수 없습니다.」
//   표: 순서 | 등급 | 이름 | 당첨 인원 | 삭제 (순서 오름차순)
//   [+ 경품 추가] [저장] (변경이 없거나 저장 중이면 막음), 알림 문구
//   【선택】 저장하지 않고 페이지를 떠나려 하면 한 번 묻는다.

