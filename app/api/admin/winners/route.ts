// PATCH /api/admin/winners — 선물 지급 처리와 취소 (spec 5.3, A-19, A-20, A-22, D-11)
//
// 의사 코드 (작업 7). 아직 구현 전이다.
//
// 【이 API 가 하는 일】
//   발표 화면의 [선물 주기]와 콘솔의 지급 체크박스가 부른다.
//   지급하면 지급 시각을 적고, 취소하면 지급 시각을 지운다.
//
// 【처리 순서】
//   1. 로그인했는지 확인한다.
//   2. 본문을 읽고 확인한다.
//      - 회차 번호: 1 이상의 정수가 아니면 400 INVALID_BODY
//      - 참가번호: 정규화한다 (normalizeParticipantNo). 틀리면 400 INVALID_PARTICIPANT_NO
//      - 지급 여부(given): 참/거짓이 아니면 400 INVALID_BODY
//   3. 회차 하나와, 그 회차에서 이 번호의 당첨 기록 한 줄을 읽는다.
//      회차가 없으면 404 DRAW_NOT_FOUND. 당첨 기록이 없으면 「없음」으로 둔다.
//   4. 지급해도 되는지 확인한다 (assertCanGiveGift).
//      - 회차가 아직 확정 전이면 409 DRAW_NOT_CONFIRMED
//      - 이 번호가 확정 당첨자가 아니면(부재자, 없는 번호) 400 INVALID_WINNER_SELECTION
//   5-가. 지급하는 경우
//      「아직 지급 시각이 비어 있을 때만」 지급 시각을 지금으로 적는다.
//      바뀐 줄이 없으면 이미 누군가 지급한 것이다 → 409 ALREADY_GIVEN.
//      두 운영자가 동시에 눌러도 DB 가 한 번만 받아 준다 (D-11). 그래서 「먼저 읽고 비어 있으면 적기」로 나누지 않는다.
//   5-나. 취소하는 경우
//      지급 시각을 지운다. 이미 비어 있어도 결과가 같으므로 오류로 보지 않는다.
//   6. 회차 번호, 참가번호, 지급 시각(취소면 비어 있음)을 돌려준다.
//
// 【이렇게 정한 이유】
//   - 5-가의 조건에 「확정 당첨자일 때만」도 함께 넣는다. 4단계에서 이미 확인했지만, 부재자에게 지급 기록이 생기는 일을
//     DB 에서 한 번 더 막는다. 비용은 없다.
//   - 지급 시각은 서버 시계로 정한다. 운영자 노트북 시계가 틀려도 올바른 시각이 남는다.

