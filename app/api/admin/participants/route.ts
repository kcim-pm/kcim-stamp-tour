//   5. 필터가 uncollected 면 「완주자 중 선물 미지급자」만 남긴다 (기능 8).
//   6. 통계, 구역 목록(zones), 참가자 목록을 돌려준다. 목록은 참가번호 순서다.
//      구역 목록은 3단계에서 함께 읽은 것을 구역 순서대로 코드와 이름만 담는다. 콘솔이 표의 열 제목으로 쓴다 (spec 5.3).
//   7. 중간에 DB 오류가 나면 500 DB_ERROR 로 돌려준다.
